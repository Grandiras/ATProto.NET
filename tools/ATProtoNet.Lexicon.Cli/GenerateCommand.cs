using System.CommandLine;
using System.Text;
using ATProtoNet.Lexicon.CodeGen;

namespace ATProtoNet.Lexicon.Cli;

public sealed partial class LexgenApp
{
    private const string GeneratedHeader = "// <auto-generated/>";
    private const string Inventory = "TypeNames.txt";

    private Command GenerateCommand()
    {
        var manifest = Manifest();
        var lexicons = new Option<string?>("--lexicons") { Description = "The Lexicons directory (default: lexicons/ next to the manifest; every *.json in it when there is no manifest)." };
        var config = new Option<string?>("--config") { Description = "The generation options (default: lexgen.json, if present)." };
        var output = new Option<string>("--out") { Description = "The output directory.", DefaultValueFactory = _ => "Generated" };
        var references = new Option<string[]>("--reference") { Description = "An assembly whose [LexiconDefinition] types resolve references (repeatable)." };
        var units = new Option<string[]>("--unit") { Description = "Write only these units of the configuration (repeatable)." };
        var check = new Option<bool>("--check") { Description = "Write nothing; exit 1 if any file would be created, changed or removed." };
        var clean = new Option<bool>("--clean") { Description = "Remove generated files that are no longer produced." };
        var command = new Command("generate", "Generates C# from Lexicons (LEX-25).") { manifest, lexicons, config, output, references, units, check, clean };
        command.SetAction((result, cancellationToken) => Generate(
            result.GetValue(manifest)!, result.GetValue(lexicons), result.GetValue(config), result.GetValue(output)!,
            result.GetValue(references) ?? [], result.GetValue(units) ?? [], result.GetValue(check), result.GetValue(clean)));
        return command;
    }

    private async Task<int> Generate(string manifestPath, string? lexicons, string? configPath, string output, string[] references, string[] units, bool check, bool clean)
    {
        var sources = ReadSources(manifestPath, lexicons);
        configPath ??= Env.Files.FileExists("lexgen.json") ? "lexgen.json" : null;
        var config = configPath is null ? new LexgenConfig() : Catch(configPath, () => LexgenConfig.Parse(Encoding.UTF8.GetString(Env.Files.ReadAllBytes(configPath))));
        var external = ExternalTypes.Read(references, Env.Files);
        var result = LexiconGenerator.Generate(sources, config, external, units.Length == 0 ? null : units);
        foreach (var diagnostic in result.Diagnostics.Where(d => d.Severity != GenerationSeverity.Info).OrderBy(d => d.File, StringComparer.Ordinal).ThenBy(d => d.Pointer, StringComparer.Ordinal))
            await Env.Error.WriteLineAsync(diagnostic.ToString());
        if (result.Diagnostics.Any(d => d.Severity == GenerationSeverity.Error))
            return result.Diagnostics.Any(d => d.Severity == GenerationSeverity.Error && d.Id.StartsWith("LXL", StringComparison.Ordinal)) ? ExitCodes.Input : ExitCodes.Findings;

        var files = result.Files.Select(f => (Path: Path.Combine(output, f.Path), Bytes: Encoding.UTF8.GetBytes(f.Text)))
            .Append((Path: Path.Combine(output, Inventory), Bytes: Encoding.UTF8.GetBytes(result.TypeNames))).ToList();
        var produced = new HashSet<string>(files.Select(f => Path.GetFullPath(f.Path)), StringComparer.Ordinal);
        // With --unit, only those units' folders are this run's to check or clean.
        var stale = (units.Length == 0 ? [output] : units.Select(u => Path.Combine(output, u)))
            .Where(Env.Files.DirectoryExists)
            .SelectMany(d => Env.Files.EnumerateFiles(d, "*.cs")).Where(f => !produced.Contains(Path.GetFullPath(f)) && IsGenerated(f)).Order(StringComparer.Ordinal).ToList();
        var changed = files.Where(f => !Env.Files.FileExists(f.Path) || !Env.Files.ReadAllBytes(f.Path).AsSpan().SequenceEqual(f.Bytes)).ToList();
        if (check)
        {
            foreach (var file in changed) await Env.Out.WriteLineAsync((Env.Files.FileExists(file.Path) ? "changed: " : "created: ") + file.Path);
            foreach (var file in stale) await Env.Out.WriteLineAsync("removed: " + file);
            return changed.Count + stale.Count == 0 ? ExitCodes.Success : ExitCodes.Findings;
        }
        foreach (var (path, bytes) in changed) Env.Files.WriteAllBytes(path, bytes);
        if (clean)
            foreach (var file in stale) Env.Files.Delete(file);
        await Env.Out.WriteLineAsync($"{result.Files.Count} files from {sources.Count} Lexicons; {changed.Count} written{(clean ? $", {stale.Count} removed" : "")}.");
        return ExitCodes.Success;
    }

    // TOO-12: only a file that carries the generated header is ever removed.
    private bool IsGenerated(string path) => Encoding.UTF8.GetString(Env.Files.ReadAllBytes(path)).StartsWith(GeneratedHeader, StringComparison.Ordinal);

    // TOO-7, TOO-9, TOO-10, TOO-13: the manifest's Lexicons, CID-checked, or every Lexicon JSON file under a directory.
    private List<LexiconSource> ReadSources(string manifestPath, string? lexicons)
    {
        var sources = new List<LexiconSource>();
        if (Env.Files.FileExists(manifestPath))
        {
            var manifest = ReadManifest(manifestPath);
            var directory = LexiconsDirectory(manifestPath, lexicons);
            foreach (var (nsid, _) in manifest.Lexicons)
            {
                var path = LexiconManifest.PathOf(directory, nsid);
                if (!Env.Files.FileExists(path)) throw new LexgenException(ExitCodes.Input, $"{path}: {nsid} is in the manifest but its file is missing.");
                var bytes = Env.Files.ReadAllBytes(path);
                var document = Catch(path, () => LexiconDocument.Parse(bytes));
                if (document.Id.ToString() != nsid) throw new LexgenException(ExitCodes.Input, $"{path}: the file's id is {document.Id}, not {nsid}.");
                if (Catch(path, document.ComputeRecordCid).ToString() != manifest.CidOf(nsid))
                    throw new LexgenException(ExitCodes.Input, $"{path}: the file does not match its CID in {manifestPath}; vendored Lexicons are never edited by hand (use install or update).");
                sources.Add(new(path, bytes, manifest.PinOf(nsid)));
            }
        }
        else
        {
            if (lexicons is null) throw new LexgenException(ExitCodes.Input, $"There is no {manifestPath} and no --lexicons directory.");
            if (!Env.Files.DirectoryExists(lexicons)) throw new LexgenException(ExitCodes.Input, $"{lexicons}: the directory does not exist.");
            foreach (var path in Env.Files.EnumerateFiles(lexicons, "*.json").Order(StringComparer.Ordinal))
            {
                var bytes = Env.Files.ReadAllBytes(path);
                if (!LooksLikeLexicon(path, bytes))
                {
                    Env.Error.WriteLine($"{path}: warning: not a Lexicon document; skipped.");
                    continue;
                }
                Catch(path, () => LexiconDocument.Parse(bytes));
                sources.Add(new(path, bytes));
            }
        }
        return sources.Count > 0 ? sources : throw new LexgenException(ExitCodes.Input, "There are no Lexicons in the input.");
    }

    // A JSON object with a "lexicon" member; any other JSON in a directory is someone else's, but a file that is not JSON is malformed.
    private static bool LooksLikeLexicon(string path, byte[] bytes)
    {
        try
        {
            using var document = System.Text.Json.JsonDocument.Parse(bytes);
            return document.RootElement.ValueKind == System.Text.Json.JsonValueKind.Object && document.RootElement.TryGetProperty("lexicon", out _);
        }
        catch (System.Text.Json.JsonException e)
        {
            throw new LexgenException(ExitCodes.Input, $"{path}: not valid JSON ({e.Message}).");
        }
    }
}
