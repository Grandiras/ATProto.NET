using System;
using System.Collections.Generic;
using System.Linq;

namespace ATProtoNet.Lexicon.CodeGen;

// Pass two: writes the C# of the planned types (LEX-38 onward).
internal sealed partial class Emitter(Planner plan)
{
    private const string Runtime = "global::ATProtoNet.Lexicon.Runtime.";
    private const string Json = "global::System.Text.Json.Serialization.";
    private const string JsonElement = "global::System.Text.Json.JsonElement";

    // Types each unit's serialization context must list beyond its own: Optional and required-union inner types, outputs, lists.
    private readonly Dictionary<PlanUnit, SortedDictionary<string, string>> _contextTypes = new();

    private string Visibility => plan.Config.Internal ? "internal" : "public";

    public string ContextClass(PlanUnit unit) => $"global::{plan.Config.RootNamespace}.{unit.Name}LexiconsJsonContext";

    // A unique contract name: the type's full name without the root namespace, "." as "_", so nesting stays distinguishable.
    public string ContextName(string typeName)
    {
        var name = typeName.StartsWith("global::", StringComparison.Ordinal) ? typeName.Substring(8) : typeName;
        if (name.StartsWith(plan.Config.RootNamespace + ".", StringComparison.Ordinal)) name = name.Substring(plan.Config.RootNamespace.Length + 1);
        return (name.EndsWith("?", StringComparison.Ordinal) ? "Nullable_" : "") + new string([.. name.Select(c => c == '.' ? '_' : c).Where(c => char.IsLetterOrDigit(c) || c == '_')]);
    }

    // The JsonTypeInfo<T> of a type in its unit's context (T must be listed there).
    public string TypeInfo(PlanUnit unit, CsType type)
    {
        Require(unit, type);
        return $"{ContextClass(unit)}.Default.{ContextName(type.Name)}";
    }

    private void Require(PlanUnit unit, CsType type)
    {
        if (!_contextTypes.TryGetValue(unit, out var set)) _contextTypes[unit] = set = new(StringComparer.Ordinal);
        set[type.Name] = type.Name is "string" or "bool" or "int" or "long" or "bool?" or "int?" or "long?" ? ""
            : ContextName(type.Name.Replace("global::System.Collections.Generic.IReadOnlyList<", "").TrimEnd('>')) + (type.IsList ? "_List" : "");
        if (type.IsList) Require(unit, type.ItemType);
    }

    public IEnumerable<KeyValuePair<string, string>> ContextTypes(PlanUnit unit) => _contextTypes.TryGetValue(unit, out var set) ? set : [];

    // One file per document: its top-level types, nested types inside them (LEX-29).
    public string Document(LexiconDocument document, IEnumerable<TypeDecl> decls, string? pin)
    {
        var writer = new CodeWriter()
            .Line($"// <auto-generated/> {document.Id}{(pin is null ? "" : " · " + pin)}")
            .Line("#nullable enable")
            .Line("#pragma warning disable CS0618 // generated code uses its own [Obsolete] members")
            .Line()
            .Line($"namespace {plan.Namespace(document.Id)};");
        var list = decls.ToList();
        foreach (var decl in list)
        {
            writer.Line();
            Decl(writer, decl);
        }
        foreach (var extended in list.SelectMany(Planner.Flatten).Where(d => d.LexiconType is not null))
            if (plan.Config.UnionExtensions.TryGetValue(extended.Path, out var unions) || extended.Path.EndsWith("#main", StringComparison.Ordinal)
                && plan.Config.UnionExtensions.TryGetValue(extended.Path.Substring(0, extended.Path.Length - 5), out unions))
                UnionExtensions(writer.Line(), extended, unions);
        return writer.ToString();
    }

    private void Decl(CodeWriter writer, TypeDecl decl)
    {
        switch (decl.Kind)
        {
            case DeclKind.MethodPart when decl.Schema is LexParams:
                Parameters(writer, decl);
                break;
            case DeclKind.Object or DeclKind.Record or DeclKind.MethodPart:
                Object(writer, decl);
                break;
            case DeclKind.Union:
                Union(writer, decl);
                break;
            case DeclKind.KnownValues:
                KnownValues(writer, decl);
                break;
            case DeclKind.Method:
                Method(writer, decl);
                break;
            case DeclKind.Tokens:
                Tokens(writer, decl);
                break;
            case DeclKind.PermissionSet:
                PermissionSet(writer, decl);
                break;
            case DeclKind.Space:
                Space(writer, decl);
                break;
        }
    }

    // <summary> from the description, or a sentence naming the definition (LEX-46), plus constraint remarks.
    private static void Docs(CodeWriter writer, string? description, string fallback, IEnumerable<string>? remarks = null)
    {
        writer.Line($"/// <summary>{(string.IsNullOrWhiteSpace(description) ? fallback : Naming.Xml(description!))}</summary>");
        var constraints = remarks?.ToList();
        if (constraints is { Count: > 0 }) writer.Line($"/// <remarks>Lexicon: {Naming.Xml(string.Join(", ", constraints))}.</remarks>");
    }

    // [LexiconDefinition], [Obsolete] and [Experimental] (LEX-46, LEX-69).
    private static void Attributes(CodeWriter writer, string? definition, string? description, string? experimental)
    {
        if (definition is not null) writer.Line($"[{Runtime}LexiconDefinition({Naming.Literal(definition)})]");
        Obsolete(writer, description);
        if (experimental is not null) writer.Line($"[global::System.Diagnostics.CodeAnalysis.Experimental({Naming.Literal(experimental)})]");
    }

    private static void Obsolete(CodeWriter writer, string? description)
    {
        if (description is not null && description.TrimStart().StartsWith("deprecated", StringComparison.OrdinalIgnoreCase))
            writer.Line($"[global::System.Obsolete({Naming.Literal(Naming.Xml(description))})]");
    }

    private static IEnumerable<string> Constraints(LexSchema schema) => schema switch
    {
        LexString s => Join(("maxLength", s.MaxLength, " (UTF-8 bytes)"), ("minLength", s.MinLength, " (UTF-8 bytes)"), ("maxGraphemes", s.MaxGraphemes, ""), ("minGraphemes", s.MinGraphemes, ""))
            .Concat(s.Const is null ? [] : [$"const \"{s.Const}\""]).Concat(s.Default is null ? [] : [$"default \"{s.Default}\""]),
        LexInteger i => Join(("minimum", i.Minimum, ""), ("maximum", i.Maximum, ""), ("const", i.Const, ""), ("default", i.Default, "")),
        LexBoolean b => b.Default is { } d ? [$"default {(d ? "true" : "false")}"] : [],
        LexArray a => Join(("minLength", a.MinLength, " items"), ("maxLength", a.MaxLength, " items")),
        LexBytes b => Join(("minLength", b.MinLength, " bytes"), ("maxLength", b.MaxLength, " bytes")),
        LexBlob b => (b.Accept is { } accept ? [$"accept {string.Join(" ", accept)}"] : Array.Empty<string>()).Concat(Join(("maxSize", b.MaxSize, " bytes"))),
        _ => [],
    };

    private static IEnumerable<string> Join(params (string Name, long? Value, string Unit)[] values) =>
        values.Where(v => v.Value is not null).Select(v => $"{v.Name} {v.Value}{v.Unit}");

    private void Tokens(CodeWriter writer, TypeDecl decl)
    {
        Docs(writer, null, $"The tokens of <c>{decl.Document.Id}</c>.");
        if (decl.Experimental is not null) writer.Line($"[global::System.Diagnostics.CodeAnalysis.Experimental({Naming.Literal(decl.Experimental)})]");
        using (writer.Block($"{Visibility} static partial class {decl.Name}"))
            foreach (var token in decl.Tokens)
            {
                writer.Separate();
                var value = token.Key == "main" ? decl.Document.Id.ToString() : decl.Document.Id + "#" + token.Key;
                Docs(writer, token.Value.Description, $"The token <c>{value}</c>.");
                Obsolete(writer, token.Value.Description);
                writer.Line($"public const string {Naming.Pascal(token.Key == "main" ? decl.Document.Id.Name : token.Key)} = {Naming.Literal(value)};");
            }
    }

    private void PermissionSet(CodeWriter writer, TypeDecl decl)
    {
        var set = (LexPermissionSet)decl.Schema!;
        Docs(writer, set.Description ?? set.Title, $"The permission set <c>{decl.Document.Id}</c>.");
        Attributes(writer, null, set.Description, decl.Experimental);
        using (writer.Block($"{Visibility} static partial class {decl.Name}"))
        {
            writer.Line("/// <summary>The permission set.</summary>")
                .Line($"public static global::ATProtoNet.Auth.PermissionSetRef Ref {{ get; }} = new(global::ATProtoNet.Nsid.Parse({Naming.Literal(decl.Document.Id.ToString())}));")
                .Line()
                .Line("/// <summary>The <c>include:</c> scope of the set.</summary>")
                .Line("/// <param name=\"audience\">The service the set's <c>rpc</c> permissions inherit as their audience, if any.</param>")
                .Line("/// <returns>The scope.</returns>")
                .Line("public static global::ATProtoNet.Auth.Scope Include(global::ATProtoNet.Xrpc.XrpcServiceRef? audience = null) => Ref.Include(audience);");
        }
    }

    private void Space(CodeWriter writer, TypeDecl decl)
    {
        var space = (LexSpace)decl.Schema!;
        Docs(writer, space.Description, $"The space type <c>{decl.Document.Id}</c>.");
        Attributes(writer, null, space.Description, decl.Experimental);
        using (writer.Block($"{Visibility} static partial class {decl.Name}"))
        {
            var names = space.NameLang is null ? "null"
                : $"new global::System.Collections.Generic.Dictionary<string, string> {{ {string.Join(", ", space.NameLang.Select(n => $"[{Naming.Literal(n.Key)}] = {Naming.Literal(n.Value)}"))} }}";
            writer.Line("/// <summary>The declaration: the space type's name and collections.</summary>")
                .Line($"public static global::ATProtoNet.Spaces.SpaceTypeDeclaration Declaration {{ get; }} = new(global::ATProtoNet.Nsid.Parse({Naming.Literal(decl.Document.Id.ToString())}), "
                    + $"{(space.Name is null ? "null" : Naming.Literal(space.Name))}, {names}, [{string.Join(", ", space.Collections.Select(Naming.Literal))}]);");
        }
    }

    // LEX-86: typed helpers for a user type that travels as LexiconUnknown in open unions declared elsewhere.
    private void UnionExtensions(CodeWriter writer, TypeDecl decl, IReadOnlyList<string> unions)
    {
        plan.UsedUnionExtensions.Add(decl.Path);
        Docs(writer, null, $"Typed access to <see cref=\"{decl.Ref}\"/> in the open unions it extends.");
        using (writer.Block($"{Visibility} static partial class {decl.Name}UnionExtensions"))
            foreach (var union in unions)
            {
                if (plan.UnionType(union) is not { } type)
                {
                    plan.Diagnostics.Add(new("ATLEX011", GenerationSeverity.Error, $"\"unionExtensions\" names {union}, which is no open union this generation or its references know.",
                        decl.Document.Id.ToString(), decl.Path));
                    continue;
                }
                using (writer.Separate().Block($"extension({type} union)"))
                {
                    writer.Line($"/// <summary>Reads the union's member as <see cref=\"{decl.Ref}\"/> when its <c>$type</c> is <c>{decl.LexiconType}</c>.</summary>")
                        .Line("/// <param name=\"value\">The member.</param>")
                        .Line("/// <returns>Whether the member is one.</returns>");
                    using (writer.Block($"public bool TryGet{decl.Name}([global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out {decl.Ref}? value)"))
                        writer.Line("value = null;")
                            .Line($"return union.Value is {Runtime}LexiconUnknown unknown && unknown.TryAs(out value);");
                    writer.Line()
                        .Line($"/// <summary>The union holding <paramref name=\"value\"/>.</summary>")
                        .Line("/// <param name=\"value\">The member.</param>")
                        .Line("/// <returns>The union.</returns>")
                        .Line($"public static {type} From{decl.Name}({decl.Ref} value) => new({Runtime}LexiconUnknown.From(value));");
                }
            }
    }
}
