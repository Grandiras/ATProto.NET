using System;
using System.Collections.Generic;
using System.Linq;

namespace ATProtoNet.Lexicon.CodeGen;

// The per-unit files: {Name}Lexicons, the serialization context and the namespace clients (LEX-30, LEX-36, LEX-66–LEX-72).
internal sealed partial class Emitter
{
    private const string Task = "global::System.Threading.Tasks.Task";
    private const string Token = "global::System.Threading.CancellationToken";
    private const string Client = "global::ATProtoNet.AtProtoClient";

    private static CodeWriter Header(string title) =>
        new CodeWriter().Line($"// <auto-generated/> {title}").Line("#nullable enable").Line("#pragma warning disable CS0618 // generated code uses its own [Obsolete] members").Line();

    public string Lexicons(PlanUnit unit)
    {
        var root = plan.Config.RootNamespace;
        var writer = Header($"{unit.Name}Lexicons")
            .Line($"[assembly: {Runtime}LexiconAssembly(typeof(global::{root}.{unit.Name}Lexicons))]")
            .Line()
            .Line($"namespace {root};")
            .Line()
            .Line($"/// <summary>The generated Lexicons of the {unit.Name} unit: their contracts and record types.</summary>");
        using (writer.Block($"{Visibility} static partial class {unit.Name}Lexicons"))
        {
            writer.Line("/// <summary>The source-generated contracts of every type of the unit.</summary>")
                .Line($"public static global::System.Text.Json.Serialization.Metadata.IJsonTypeInfoResolver Resolver => {ContextClass(unit)}.Default;")
                .Line()
                .Line("/// <summary>Adds the unit's record types to a registry.</summary>")
                .Line("/// <param name=\"registry\">The registry.</param>");
            using (writer.Block($"public static void Register({Runtime}LexiconTypeRegistry registry)"))
            {
                writer.Line("global::System.ArgumentNullException.ThrowIfNull(registry);");
                foreach (var record in unit.Decls.SelectMany(Planner.Flatten).Where(d => d.Kind == DeclKind.Record))
                {
                    if (record.Experimental is { } id) writer.Line($"#pragma warning disable {id}");
                    writer.Line($"registry.AddRecord<{record.Ref}>();");
                    if (record.Experimental is { } restore) writer.Line($"#pragma warning restore {restore}");
                }
            }
        }
        return writer.ToString();
    }

    // LEX-72: one source-generated context per unit, listing every type its code asks for by name.
    public string Context(PlanUnit unit)
    {
        foreach (var decl in unit.Decls.SelectMany(Planner.Flatten).Where(d => d.Kind is DeclKind.Object or DeclKind.Record or DeclKind.Union or DeclKind.KnownValues
                     || d.Kind == DeclKind.MethodPart && d.Schema is not LexParams))
            Require(unit, Planner.Of(decl));
        var experimental = unit.Decls.SelectMany(Planner.Flatten).Select(d => d.Experimental).Where(e => e is not null).Distinct().ToList();
        var writer = Header($"{unit.Name}LexiconsJsonContext");
        foreach (var id in experimental) writer.Line($"#pragma warning disable {id}");
        writer.Line($"namespace {plan.Config.RootNamespace};")
            .Line()
            .Line($"[{Json}JsonSourceGenerationOptions(DefaultIgnoreCondition = {Json}JsonIgnoreCondition.WhenWritingNull, NumberHandling = {Json}JsonNumberHandling.Strict,")
            .Line("    PropertyNameCaseInsensitive = false, RespectNullableAnnotations = true)]");
        foreach (var type in ContextTypes(unit).OrderBy(t => t.Value, StringComparer.Ordinal))
            writer.Line(type.Value.Length == 0 ? $"[{Json}JsonSerializable(typeof({type.Key}))]" : $"[{Json}JsonSerializable(typeof({type.Key}), TypeInfoPropertyName = {Naming.Literal(type.Value)})]");
        writer.Line($"internal sealed partial class {unit.Name}LexiconsJsonContext : {Json}JsonSerializerContext;");
        return writer.ToString();
    }

    private sealed class Group(string prefix)
    {
        public string Prefix { get; } = prefix;
        public SortedDictionary<string, Group> Children { get; } = new(StringComparer.Ordinal);
        public List<TypeDecl> Methods { get; } = [];
    }

    // LEX-36, LEX-66, LEX-67: a struct per NSID group, reached from the client through the accessors.
    public string Namespaces(PlanUnit unit)
    {
        var roots = new SortedDictionary<string, Group>(StringComparer.Ordinal);
        foreach (var method in unit.Decls.Where(d => d.Kind == DeclKind.Method && d.Schema is not LexSubscription))
        {
            var group = method.Document.Id.Authority;
            var root = plan.Config.Accessors.Keys.Where(k => group == k || group.StartsWith(k + ".", StringComparison.Ordinal)).OrderByDescending(k => k.Length).FirstOrDefault()
                ?? string.Join(".", group.Split('.').Take(2));
            if (!roots.TryGetValue(root, out var node)) roots[root] = node = new(root);
            foreach (var segment in group.Length > root.Length ? group.Substring(root.Length + 1).Split('.') : [])
            {
                if (!node.Children.TryGetValue(segment, out var child)) node.Children[segment] = child = new(node.Prefix + "." + segment);
                node = child;
            }
            node.Methods.Add(method);
        }
        var writer = Header($"{unit.Name} namespace clients");
        foreach (var root in roots.Values)
        {
            var accessor = plan.Config.Accessors.TryGetValue(root.Prefix, out var name) ? name : Naming.Pascal(root.Prefix.Split('.')[1]);
            if (accessor == "@root")
            {
                if (root.Methods.Count > 0) throw new InvalidOperationException($"Methods directly under the @root prefix {root.Prefix} have no namespace struct.");
                writer.Line("namespace ATProtoNet").Line("{");
                using (writer.Block("public partial class AtProtoClient"))
                    foreach (var child in root.Children.Values)
                    {
                        writer.Separate().Line($"/// <summary>The <c>{child.Prefix}</c> methods.</summary>")
                            .Line($"public {StructRef(child)} {Naming.Pascal(child.Prefix.Split('.').Last())} => new(this);");
                    }
                writer.Line("}").Line();
                foreach (var child in root.Children.Values) Struct(writer, child);
                continue;
            }
            writer.Line($"namespace {Namespace(root.Prefix)}").Line("{");
            writer.Line($"    /// <summary>The <c>client.{accessor}</c> accessor of the <c>{root.Prefix}</c> methods.</summary>");
            writer.Line($"    {Visibility} static partial class {accessor}ClientExtensions").Line("    {");
            writer.Line($"        extension({Client} client)").Line("        {");
            writer.Line($"            /// <summary>The <c>{root.Prefix}</c> methods.</summary>");
            writer.Line($"            public {StructRef(root)} {accessor} => new(client);").Line("        }").Line("    }").Line("}").Line();
            Struct(writer, root);
        }
        return writer.ToString().TrimEnd('\n') + "\n";
    }

    private string Namespace(string prefix) => plan.Config.RootNamespace + string.Concat(prefix.Split('.').Select(s => "." + Naming.Pascal(s)));

    private string StructRef(Group group) => $"global::{Namespace(group.Prefix)}.{Naming.Pascal(group.Prefix.Split('.').Last())}Namespace";

    private void Struct(CodeWriter writer, Group group)
    {
        var name = Naming.Pascal(group.Prefix.Split('.').Last()) + "Namespace";
        writer.Line($"namespace {Namespace(group.Prefix)}").Line("{");
        writer.Line($"    /// <summary>The <c>{group.Prefix}</c> methods.</summary>")
            .Line("    /// <param name=\"client\">The client the methods call.</param>")
            .Line($"    {Visibility} readonly partial struct {name}({Client} client)").Line("    {");
        var body = new CodeWriter();
        foreach (var child in group.Children.Values)
            body.Separate().Line($"/// <summary>The <c>{child.Prefix}</c> methods.</summary>")
                .Line($"public {StructRef(child)} {Naming.Pascal(child.Prefix.Split('.').Last())} => new(client);");
        foreach (var method in group.Methods.OrderBy(m => m.Name, StringComparer.Ordinal)) ClientMethod(body.Separate(), method);
        foreach (var line in body.ToString().TrimEnd('\n').Split('\n')) writer.Line(line.Length == 0 ? "" : "        " + line);
        writer.Line("    }").Line("}").Line();
        foreach (var child in group.Children.Values) Struct(writer, child);
    }

    private void ClientMethod(CodeWriter writer, TypeDecl method)
    {
        var shape = Shape(method);
        var descriptor = $"{method.Ref}.Descriptor";
        var parameters = new List<string>();
        var arguments = new List<string> { descriptor };
        var bothRequired = shape is { Parameters: not null, Input: not null } && !shape.InputOptional;
        if (shape.Parameters is not null)
        {
            var optional = shape.ParametersOptional && !bothRequired;
            parameters.Add(optional ? $"{shape.Parameters}? parameters = null" : $"{shape.Parameters} parameters");
            arguments.Add(optional ? "parameters ?? new()" : "parameters");
        }
        else if (shape.Kind == "query") arguments.Add($"new {Empty}()");
        if (shape.Input is not null)
        {
            parameters.Add(shape.InputOptional ? $"{shape.Input}? input = null" : $"{shape.Input} input");
            arguments.Add(shape.InputOptional ? "input ?? new()" : "input");
        }
        else if (shape.Kind == "procedure") arguments.Add($"new {Empty}()");
        parameters.Add($"{Token} cancellationToken = default");
        arguments.Add("cancellationToken");
        var returns = shape.Output is null && shape.Kind == "procedure" ? Task : $"{Task}<{shape.Output ?? Empty}>";
        var call = shape.Kind == "query" ? "QueryAsync" : "ProcedureAsync";
        var member = method.Name;

        Docs(writer, method.Schema!.Description, $"Calls <c>{method.Document.Id}</c>.");
        ParamDocs(writer, shape);
        writer.Line($"/// <returns>{(returns == Task ? "When the call succeeds." : "The output.")}</returns>");
        Attributes(writer, null, method.Schema.Description, method.Experimental);
        writer.Line($"public {returns} {member}Async({string.Join(", ", parameters)}) =>")
            .Line($"    client.{call}({string.Join(", ", arguments)});");
        if (shape.Item is not { } item) return;

        var words = Naming.SplitWords(member);
        var enumerate = "Enumerate" + (words.Count > 1 && words[0] is "Get" or "List" ? string.Concat(words.Skip(1)) : member) + "Async";
        writer.Line()
            .Line($"/// <summary>Enumerates every item of <c>{method.Document.Id}</c>, page by page.</summary>");
        ParamDocs(writer, shape with { Input = null });
        writer.Line("/// <returns>The items.</returns>");
        Attributes(writer, null, method.Schema.Description, method.Experimental);
        using (writer.Block($"public global::System.Collections.Generic.IAsyncEnumerable<{item.Name}> {enumerate}({parameters[0]}, {Token} cancellationToken = default)"))
            writer.Line("var c = client;")
                .Line(shape.ParametersOptional ? "var p = parameters ?? new();" : "var p = parameters;")
                .Line($"return {Xrpc}Pagination.EnumerateAsync<{shape.Output}, {item.Name}>((cursor, token) => c.QueryAsync({descriptor}, p with {{ Cursor = cursor }}, token), cancellationToken);");
    }

    private static void ParamDocs(CodeWriter writer, MethodShape shape)
    {
        if (shape.Parameters is not null) writer.Line("/// <param name=\"parameters\">The query parameters.</param>");
        if (shape.Input is not null) writer.Line("/// <param name=\"input\">The input.</param>");
        writer.Line("/// <param name=\"cancellationToken\">Cancels the call.</param>");
    }
}
