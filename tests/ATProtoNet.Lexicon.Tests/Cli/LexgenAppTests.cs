    [Fact]
    [Trait("Spec", "TOO-4")]
    [Trait("Spec", "TOO-19")]
    public async Task Lint_FormatJson_PrintsTheDiagnostics()
    {
        Write("in/authFull.json", TodoAuthFull.Replace("\"description\": \"Full access to to-do items.\",", "", StringComparison.Ordinal));

        var (exitCode, output, _) = await RunAsync("lint", "in", "--format", "json");

        Assert.Equal(ExitCodes.Success, exitCode);
        var report = JsonNode.Parse(output)!;
        Assert.Equal(0, (int)report["errors"]!);
        var diagnostic = Assert.Single(report["diagnostics"]!.AsArray())!;
        Assert.Equal("com.example.todo.authFull", (string?)diagnostic["nsid"]);
        Assert.Equal("warning", (string?)diagnostic["severity"]);
        Assert.StartsWith("LXL", (string?)diagnostic["rule"], StringComparison.Ordinal);
        Assert.StartsWith("/defs/main", (string?)diagnostic["pointer"], StringComparison.Ordinal);
    }

