    // Writes documents under lexicons/ with a manifest listing them under a directory source.
    private void Vendor(params string[] documents)
    {
        var manifest = LexiconManifest.Empty();
        foreach (var text in documents)
        {
            var document = LexiconDocument.Parse(System.Text.Encoding.UTF8.GetBytes(text));
            Write(LexiconManifest.PathOf("lexicons", document.Id.ToString()), text);
            manifest.Set(document.Id.ToString(), "local", document.ComputeRecordCid().ToString());
        }
        manifest.Sources["local"] = new JsonObject { ["type"] = "directory", ["path"] = "proposals" };
        Files.WriteAllBytes("lexicons.json", manifest.ToUtf8());
    }
