using System.Text;
using ATProtoNet.Lexicon.CodeGen;
using ATProtoNet.TestKit;

namespace ATProtoNet.Lexicon.Tests.CodeGen;

// The emitter's output for the representative set in Golden/ is reviewed and committed; any change shows up here (LEX-25, LEX-29).
// Regenerate after an intended change with:
//   atproto-lexgen generate --manifest none --lexicons tests/ATProtoNet.Lexicon.Tests/Golden/lexicons \
//     --config tests/ATProtoNet.Lexicon.Tests/Golden/lexgen.json --out tests/ATProtoNet.Lexicon.Tests/Golden/expected
public sealed class GoldenTests
{
    private static readonly string Golden = RepositoryFiles.PathOf("tests/ATProtoNet.Lexicon.Tests/Golden");

    public static GenerationResult Generate() => LexiconGenerator.Generate(
        [.. Directory.EnumerateFiles(Path.Combine(Golden, "lexicons"), "*.json", SearchOption.AllDirectories).Order(StringComparer.Ordinal).Select(f => new LexiconSource(f, File.ReadAllBytes(f)))],
        LexgenConfig.Parse(File.ReadAllText(Path.Combine(Golden, "lexgen.json"))));

    public static TheoryData<string> ExpectedFiles() =>
        [.. Directory.EnumerateFiles(Path.Combine(Golden, "expected"), "*", SearchOption.AllDirectories).Select(f => Path.GetRelativePath(Path.Combine(Golden, "expected"), f).Replace('\\', '/')).Order(StringComparer.Ordinal)];

    [Theory]
    [Trait("Spec", "LEX-25")]
    [MemberData(nameof(ExpectedFiles))]
    public void Generate_GoldenSet_MatchesTheCommittedFile(string path)
    {
        var result = Generate();
        var actual = path == "TypeNames.txt" ? result.TypeNames : result.Files.Single(f => f.Path == path).Text;

        Assert.Equal(File.ReadAllText(Path.Combine(Golden, "expected", path)), actual);
    }

    [Fact]
    [Trait("Spec", "LEX-29")]
    public void Generate_GoldenSet_ProducesOnlyCommittedFilesWithoutWarnings()
    {
        var result = Generate();

        Assert.Empty(result.Diagnostics.Where(d => d.Severity != GenerationSeverity.Info).Select(d => d.ToString()));
        Assert.Equal(ExpectedFiles().Select(row => row.Data).Where(p => p != "TypeNames.txt"), result.Files.Select(f => f.Path));
    }

    [Fact]
    [Trait("Spec", "LEX-29")]
    public void Generate_SameInputsInAnotherOrder_IsByteIdentical()
    {
        var sources = Directory.EnumerateFiles(Path.Combine(Golden, "lexicons"), "*.json", SearchOption.AllDirectories).Select(f => new LexiconSource(f, File.ReadAllBytes(f))).ToList();
        var config = LexgenConfig.Parse(File.ReadAllText(Path.Combine(Golden, "lexgen.json")));

        var forward = LexiconGenerator.Generate([.. sources.OrderBy(s => s.Path, StringComparer.Ordinal)], config);
        var backward = LexiconGenerator.Generate([.. sources.OrderByDescending(s => s.Path, StringComparer.Ordinal)], config);

        Assert.Equal(forward.Files.Select(f => f.Text), backward.Files.Select(f => f.Text));
    }

    [Fact]
    [Trait("Spec", "LEX-29")]
    public void Generate_EveryFile_StartsWithTheHeaderAndQualifiesTypes()
    {
        foreach (var file in Generate().Files)
        {
            Assert.StartsWith("// <auto-generated/>", file.Text);
            Assert.Contains("#nullable enable", file.Text);
            Assert.DoesNotContain("\nusing ", file.Text);
            Assert.DoesNotContain("\r", file.Text);
        }
    }

    [Fact]
    [Trait("Spec", "LEX-89")]
    public void Generate_FirstPartyLexicons_RaisesNoWarnings()
    {
        var manifest = System.Text.Json.Nodes.JsonNode.Parse(File.ReadAllText(RepositoryFiles.PathOf("lexicons.json")))!["lexicons"]!.AsObject();
        var sources = manifest.Select(e => RepositoryFiles.PathOf("lexicons/" + e.Key.Replace('.', '/') + ".json")).Select(f => new LexiconSource(f, File.ReadAllBytes(f))).ToList();

        var result = LexiconGenerator.Generate(sources, LexgenConfig.Parse(File.ReadAllText(RepositoryFiles.PathOf("lexgen.json"))), units: []);

        Assert.Empty(result.Diagnostics.Where(d => d.Severity != GenerationSeverity.Info).Select(d => d.ToString()));
        Assert.Equal(File.ReadAllText(RepositoryFiles.PathOf("src/ATProtoNet/Generated/TypeNames.txt")), result.TypeNames);
    }

    [Fact]
    [Trait("Spec", "LEX-28")]
    public void Generate_FirstPartyAtProto_MatchesTheCheckedInCode()
    {
        var generated = RepositoryFiles.PathOf("src/ATProtoNet/Generated");
        var manifest = ATProtoNet.Lexicon.Cli.LexiconManifest.Parse(File.ReadAllBytes(RepositoryFiles.PathOf("lexicons.json")));
        var sources = manifest.Lexicons.Select(e => (e.Key, File: RepositoryFiles.PathOf("lexicons/" + e.Key.Replace('.', '/') + ".json")))
            .Select(e => new LexiconSource(e.File, File.ReadAllBytes(e.File), manifest.PinOf(e.Key))).ToList();

        var result = LexiconGenerator.Generate(sources, LexgenConfig.Parse(File.ReadAllText(RepositoryFiles.PathOf("lexgen.json"))), ATProtoNet.Lexicon.Cli.ExternalTypes.Read([], new ATProtoNet.Lexicon.Cli.PhysicalFileSystem()), ["AtProto"]);

        var stale = result.Files.Where(f => !File.Exists(Path.Combine(generated, f.Path)) || File.ReadAllText(Path.Combine(generated, f.Path), Encoding.UTF8) != f.Text).Select(f => f.Path);
        Assert.Empty(stale);
        Assert.Equal(result.Files.Count, Directory.EnumerateFiles(Path.Combine(generated, "AtProto"), "*.cs").Count());
    }
}
